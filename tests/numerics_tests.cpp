void check(bool result,const char* message) {if(!result) throw std::runtime_error{message};}
void ledger(const World& w) {
    const auto& s=w.statistics();
    check(s.finite&&std::abs(s.mass_error)<1e-5&&std::abs(s.energy_error)<1e-3,"Conservation/finite state");
}
void manufactured_pressure() {
    detail::State s;s.allocate();
    auto& l=s.liquid;
    constexpr int nx=96,ny=64;
    std::vector<double> exact(grid_cells);
    for(int y=0;y<ny;++y) for(int x=0;x<nx;++x) {
        const int i=(y+8)*grid_width+x+8;
        l.wet.push_back(i);l.mask[i]=1;
        exact[i]=std::sin(std::numbers::pi*(x+1)/(nx+1))*std::sin(std::numbers::pi*(y+1)/(ny+1));
    }
    // Build a variable-coefficient, symmetric Dirichlet operator independently
    // from the projection assembly. The known solution is not generated by PCG.
    for(int i=0;i<grid_cells;++i) {
        l.right[i]=1+.2*std::sin(i*.07);l.down[i]=1+.3*std::cos(i*.13);
    }
    for(const int i:l.wet) {
        l.diagonal[i]=l.right[i-1]+l.right[i]+l.down[i-grid_width]+l.down[i];
        l.rhs[i]=l.diagonal[i]*exact[i]-l.right[i-1]*exact[i-1]-l.right[i]*exact[i+1]
            -l.down[i-grid_width]*exact[i-grid_width]-l.down[i]*exact[i+grid_width];
    }
    s.config.pressure_tolerance=1e-10;s.config.pressure_iterations=1000;
    int ic_iterations=0;
    for(int mode:{0,1,2}) {
        const bool modified=mode>0;
        s.config.coarse_pressure=mode==2;
        s.config.modified_cholesky=modified;s.report={};std::ranges::fill(l.pressure,0.0);
        detail::solve_compact_pressure(s);
        double error=0,residual=0,norm=0;
        for(const int i:l.wet) {
            error=std::max(error,std::abs(l.pressure[i]-exact[i]));
            const double r=l.rhs[i]-(l.diagonal[i]*l.pressure[i]-l.right[i-1]*l.pressure[i-1]
                -l.right[i]*l.pressure[i+1]-l.down[i-grid_width]*l.pressure[i-grid_width]-l.down[i]*l.pressure[i+grid_width]);
            residual+=r*r;norm+=l.rhs[i]*l.rhs[i];
        }
        residual=std::sqrt(residual)/std::max(1.0,std::sqrt(norm));
        check(error<1e-7&&residual<=1e-10&&s.report.pressure_converged,"Manufactured Poisson solution/true residual");
        if(!modified) ic_iterations=s.report.pressure_iterations;
        else check(s.report.pressure_iterations<ic_iterations,"MIC should reduce iterations on a smooth Poisson problem");
        std::cout<<(mode==2?"MIC+coarse":modified?"MIC":"IC")<<" iterations="<<s.report.pressure_iterations<<" error="<<error<<" true residual="<<residual<<'\n';
    }
}
void serial_parallel() {
    for(const auto scene:{Scene::dam_break,Scene::smoke_vent,Scene::wood_fire,Scene::quench_metal}) {
        PhysicsConfig serial;serial.worker_threads=1;
        auto parallel=serial;parallel.worker_threads=4;
        World a{222,serial},b{222,parallel};a.load_scene(scene);b.load_scene(scene);
        for(int n=0;n<30;++n) {
            a.step();b.step();
            check(a.checksum()==b.checksum(),"Serial/parallel state must be bitwise equal");
            ledger(a);ledger(b);
        }
    }
    // A 2-lane partition must also match; dispatch repeatedly, reset, shut down.
    PhysicsConfig a;a.worker_threads=1;auto b=a;b.worker_threads=2;
    for(int repeat=0;repeat<4;++repeat) {
        World serial{42,a},parallel{42,b};
        serial.load_scene(Scene::ice_fire);parallel.load_scene(Scene::ice_fire);
        for(int n=0;n<8;++n){serial.step();parallel.step();}
        check(serial.checksum()==parallel.checksum(),"Two-lane executor/reset equivalence");
    }
}
void thermal_maximum_principle() {
    // Low heat-capacity solids surrounded by hot gas stress concurrent contact
    // fluxes: capping each face separately used to allow a total above C/dt.
    PhysicsConfig c;c.worker_threads=1;c.air=c.fluids=c.motion=c.reactions=false;
    c.heat_contact=1000;
    World w{13,c};
    for(int y=90;y<96;++y) for(int x=100;x<106;++x)
        w.set({x,y},Material::metal,200,.0005);
    for(int y=88;y<98;++y) for(int x=98;x<108;++x)
        if(w.at({x,y}).material==Material::empty) w.set({x,y},Material::smoke,700,.1);
    for(int n=0;n<40;++n) {
        w.step();ledger(w);
        for(int y=88;y<98;++y) for(int x=98;x<108;++x) {
            const auto p=w.sample({x,y});
            check(p.temperature>=200-1e-6&&p.temperature<=700+1e-6,"Thermal discrete maximum principle");
            check(p.air_temperature>=200-1e-6&&p.air_temperature<=700+1e-6,"Gas contact maximum principle");
        }
    }
}
void sealed_components() {
    PhysicsConfig c;c.worker_threads=1;c.thermal=c.air=c.reactions=c.motion=false;c.open_top=false;
    World w{5,c};
    for(int base:{35,85}) {
        for(int y=40;y<=62;++y) for(int x=base;x<=base+20;++x)
            w.set({x,y},(y==40||y==62||x==base||x==base+20)?Material::metal:Material::water);
    }
    const double mass=w.mass_of(Material::water);
    for(int n=0;n<30;++n) {
        w.step();ledger(w);
        check(w.statistics().pressure_converged,"Sealed components must converge");
        check(w.statistics().max_divergence<.02,"A gauge must not become a volume source");
    }
    check(std::abs(w.mass_of(Material::water)-mass)<1e-8,"Sealed mass conservation");
    for(int base:{35,85}) {
        const double dp=w.sample({base+5,50}).liquid_pressure-w.sample({base+5,43}).liquid_pressure;
        check(std::abs(dp-7*c.gravity)<.1,"Independent hydrostatic pressure gauges");
    }
}
void hot_fuel_activation() {
    PhysicsConfig c;c.worker_threads=1;c.thermal=c.air=c.motion=c.fluids=false;
    World w{10,c};w.set({90,80},Material::gas,1800);
    // The renderer classifies this hot mixture as flame. Chemistry must inspect
    // the fuel species, not depend on the visual dominant-material classifier.
    const double fuel=w.mass_of(Material::gas);
    w.step();ledger(w);
    check(w.mass_of(Material::gas)<fuel,"Hot fuel must react even when displayed as flame");
    World cold{10,c};cold.set({90,80},Material::gas,300);
    const double initial=cold.mass_of(Material::gas);cold.step();
    check(cold.mass_of(Material::gas)==initial,"Cold fuel must remain inert");ledger(cold);
}
void timestep_refinement() {
    PhysicsConfig c;c.worker_threads=1;c.thermal=c.air=c.motion=c.reactions=false;
    auto refined=c;refined.liquid_cfl=.45;
    World coarse{3,c},fine{3,refined};
    for(int y=50;y<60;++y) for(int x=120;x<140;++x) {
        coarse.set({x,y},Material::water);fine.set({x,y},Material::water);
    }
    for(int n=0;n<30;++n){coarse.step();fine.step();}
    auto center=[](const World& world) {
        double moment=0,mass=0;
        for(int y=0;y<grid_height;++y) for(int x=0;x<grid_width;++x) {
            const double volume=world.sample({x,y}).liquid_fractions[0];
            mass+=volume;moment+=volume*y;
        }
        return moment/mass;
    };
    const double coarse_center=center(coarse),fine_center=center(fine);
    const double difference=std::abs(coarse_center-fine_center);
    std::cout<<"Centers "<<coarse_center<<" / "<<fine_center<<'\n';
    std::cout<<"CFL .9/.45 falling-water center difference="<<difference<<" cells\n";
    check(difference<.35,"CFL refinement should preserve a falling body's trajectory");ledger(coarse);ledger(fine);
    const double ballistic=54.5+.5*c.gravity*.5*.5;
    check(std::abs(coarse_center-ballistic)<1&&std::abs(fine_center-ballistic)<1,"Falling liquid follows gravity, not one cell per substep");
    c.liquid_cfl=0;bool rejected=false;
    try {World invalid{1,c};} catch(const std::invalid_argument&) {rejected=true;}
    check(rejected,"Reject invalid CFL before scheduling any worker");
}
